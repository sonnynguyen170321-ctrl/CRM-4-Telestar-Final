/** Folded the same way the normalizer folds: NFC, diacritics stripped, lower case, single spaces. */
function fold(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

/** Every canonical country name, sorted. */
export const ALL_COUNTRIES: readonly string[] = COUNTRY_ROWS.map((row) => row[1]).sort();

/** Folded spelling -> canonical name: the name itself and every alias. */
export const COUNTRY_SPELLINGS: Readonly<Record<string, string>> = (() => {
  const out: Record<string, string> = {};
  for (const [, canonical, ...aliases] of COUNTRY_ROWS) {
    out[fold(canonical)] = canonical;
    for (const alias of aliases) out[fold(alias)] = canonical;
  }
  return out;
})();

/** Folded alpha-2 code -> canonical name ("de" -> "Germany"; "gb" and "uk" both -> United Kingdom). */
export const ISO2_TO_COUNTRY: Readonly<Record<string, string>> = (() => {
  const out: Record<string, string> = { uk: "United Kingdom" };
  for (const [code, canonical] of COUNTRY_ROWS) out[code.toLowerCase()] = canonical;
  return out;
})();

