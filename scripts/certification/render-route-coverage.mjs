/**
 * Write down every API route and the test that would notice if it broke.
 *
 *     node scripts/certification/render-route-coverage.mjs
 *
 * The audits kept missing things that a list would not have. `POST /api/sequences` had no test at
 * all and 500'd on every call for as long as it has existed; the inbox read and wrote across the
 * whole company because the role matrix in `e2e/roles/role-negative-access.spec.ts` covers
 * `/admin`, the lead pool and import/export — and stops there. Nothing said which routes the
 * matrix did *not* reach, so nobody could see the hole.
 *
 * This regenerates the inventory from the filesystem. `tests/route-coverage.test.ts` then fails
 * when a route appears with no net and no written reason, which is the part that survives the next
 * person forgetting. Hand-written `reason:` lines are preserved across regeneration — they are the
 * only part a human owns.
 *
 * A route counts as covered when a vitest file imports its handler (`@/app/api/…/route`) or an e2e
 * spec addresses its path. Neither proves the test is any good; both prove someone looked.
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = process.cwd();
const API_DIR = join(ROOT, 'app', 'api');
const MANIFEST = join(ROOT, '.agent', 'registry', 'route-coverage.yaml');
const TEST_DIRS = [join(ROOT, 'tests'), join(ROOT, 'e2e')];

const MUTATING = ['POST', 'PATCH', 'PUT', 'DELETE'];

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (entry === 'route.ts') out.push(full);
  }
  return out;
}

function walkTests(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walkTests(full, out);
    else if (/\.(test|spec)\.(ts|tsx)$/.test(entry)) out.push(full);
  }
  return out;
}

/** `app/api/leads/[id]/route.ts` -> `leads/[id]` */
function routeKey(file) {
  return relative(API_DIR, file).split(sep).slice(0, -1).join('/');
}

/** The part of a path before any dynamic segment — what an e2e spec can match on literally. */
function staticPrefix(key) {
  const idx = key.indexOf('[');
  return idx === -1 ? key : key.slice(0, idx).replace(/\/$/, '');
}

function methodsOf(source) {
  const found = new Set();
  for (const m of [...MUTATING, 'GET']) {
    if (new RegExp(`export\\s+(async\\s+)?function\\s+${m}\\b`).test(source)) found.add(m);
    if (new RegExp(`export\\s+const\\s+${m}\\b`).test(source)) found.add(m);
  }
  return [...found].sort();
}

/** Preserve the `reason:` a human wrote for an uncovered route. */
function existingReasons() {
  if (!existsSync(MANIFEST)) return new Map();
  const reasons = new Map();
  let current = null;
  for (const line of readFileSync(MANIFEST, 'utf8').split('\n')) {
    const path = line.match(/^\s*-\s+path:\s+(\S+)/);
    if (path) current = path[1];
    const reason = line.match(/^\s*reason:\s+(.+)$/);
    if (reason && current) reasons.set(current, reason[1].trim());
  }
  return reasons;
}

const routeFiles = walk(API_DIR).sort();
const testFiles = walkTests(TEST_DIRS[0]).concat(walkTests(TEST_DIRS[1]));
const testSources = testFiles.map((f) => ({ file: relative(ROOT, f).split(sep).join('/'), text: readFileSync(f, 'utf8') }));
const reasons = existingReasons();

const rows = routeFiles.map((file) => {
  const key = routeKey(file);
  const source = readFileSync(file, 'utf8');
  const methods = methodsOf(source);
  const prefix = staticPrefix(key);

  const covering = testSources
    .filter(({ text }) =>
      text.includes(`@/app/api/${key}/route`) ||
      text.includes(`app/api/${key}/route`) ||
      (prefix.length > 0 && text.includes(`/api/${prefix}`))
    )
    .map(({ file: f }) => f)
    .sort();

  return {
    path: `app/api/${key}/route.ts`,
    methods,
    mutating: methods.some((m) => MUTATING.includes(m)),
    tests: covering,
    reason: reasons.get(`app/api/${key}/route.ts`) ?? null,
  };
});

const uncovered = rows.filter((r) => r.mutating && r.tests.length === 0);

const lines = [
  '# API route coverage — generated by scripts/certification/render-route-coverage.mjs',
  '#',
  '# One line per route, and the tests that would notice if it broke. A route counts as covered',
  '# when a vitest file imports its handler or an e2e spec addresses its path — which proves',
  '# someone looked, not that the test is good.',
  '#',
  '# `tests/route-coverage.test.ts` fails when a mutating route has neither a test nor a written',
  '# `reason`. Add the reason by hand; regeneration keeps it.',
  '#',
  `# routes: ${rows.length}   mutating: ${rows.filter((r) => r.mutating).length}   ` +
    `mutating without a test: ${uncovered.length}`,
  'routes:',
];

for (const row of rows) {
  lines.push(`  - path: ${row.path}`);
  lines.push(`    methods: [${row.methods.join(', ')}]`);
  if (row.tests.length > 0) {
    lines.push('    tests:');
    for (const t of row.tests) lines.push(`      - ${t}`);
  } else {
    lines.push('    tests: []');
  }
  if (row.reason) lines.push(`    reason: ${row.reason}`);
}

writeFileSync(MANIFEST, lines.join('\n') + '\n', 'utf8');

console.log(`routes            : ${rows.length}`);
console.log(`mutating          : ${rows.filter((r) => r.mutating).length}`);
console.log(`mutating uncovered: ${uncovered.length}`);
for (const r of uncovered.slice(0, 20)) console.log(`  - ${r.path} [${r.methods.join(', ')}]`);
if (uncovered.length > 20) console.log(`  … and ${uncovered.length - 20} more`);
